#!/usr/bin/env python
"""c10 `management_replay` family: rebuild + relabel on the current reward engine.

WHAT WAS WRONG WITH THE c8 FAMILY (all three defects reproduced, not assumed):

 1. POST-ACTION STATE. `build_replay_v2.py` applied the action to the accounting
    ledger BEFORE it rendered the prompt, so the position state the model was
    shown is the state AFTER the trade it is being asked about. Measured on the
    c8 train split: every one of the 11,660 EXIT-labelled rows shows
    `inventory: 0` - a FLAT position - so 38.5% of the corpus asked "what do you
    do with your position?" while showing no position, and the label was implied
    by the state rather than earned from it. ADD/REDUCE rows were likewise shown
    the post-trade size.

 2. WRONG BASIS. Labels came from the retired `replay_v2.0_constant_notional`
    heuristic (180 bp one-way, fixed risk budget), not from the reward engine that
    RL grades with, so SFT and RL disagreed about what "good" means.

 3. WRONG LABEL SEMANTICS. The candidate table in `grpo_reward_bridge` began
    REDUCE with HOLD, so "REDUCE" was graded as a hold-then-reduce trajectory.

This builder fixes all three at once:
 * the position state is the state at the DECISION INSTANT (pre-action), recovered
   exactly by inverting the archived accounting and CHECKED against the recorded
   post-action numbers of the next row in the episode (a 100% match is required;
   any mismatch is reported, never smoothed);
 * every candidate is valued from that SAME held state by
   `reward_engine.score_action_sequence(entry=...)`, the reward authority RL uses;
 * label = argmax over the four candidates, with per-candidate refusals counted.

HISTORY IS NOT THE AUTHORITY for the label. The recovered trajectory is used only
to place the decision in a real position; the label is recomputed from scratch.

Run:
  /home/alon/qwen27b-venv/bin/python build_management_c10.py --splits train validation examination
"""
