CAPITAL_SOL = 1.0
ENTRY_TRANCHE_SOL = 0.5
OW = 0.018                      # the ARCHIVED one-way cost, used ONLY to invert history
MIN_NOTIONAL_LAMPORTS = 100_000  # house tape filter (every production scorer uses it)
MAX_PX_RATIO = 50

# One cost statement for the whole corpus, generated by the single authority so no call
# site can reintroduce a hand-typed figure. See cost_authority.py.
COST_MODEL = CA.model_statement()

# c8 (ARCHIVED) prompt vocabulary - the parser must read the archive as it was written,
# and the new prompt is rendered separately (RE_MARK_NEW below).
RE_PRICE_ENTRY = re.compile(r"price_lamports_per_raw_token=([0-9.eE+-]+)")
RE_MARK = re.compile(r"mark price \(SOL per raw token\): ([0-9.eE+-]+)")
RE_MARK_NEW = re.compile(r"mark price \(lamports per raw token\): ([0-9.eE+-]+)")
RE_ENTRY = re.compile(r"entry price: ([0-9.eE+-]+)")
RE_HOLD = re.compile(r"holding time: ([0-9.]+) s")
RE_MFE = re.compile(r"max favourable so far: ([0-9.eE+-]+) bp")
RE_MAE = re.compile(r"max adverse so far: ([0-9.eE+-]+) bp")
RE_INV = re.compile(r"inventory: ([0-9.eE+-]+) raw tokens")
RE_CASH = re.compile(r"cash: ([0-9.eE+-]+) SOL")

SYSTEM = ("You are an on-chain position manager for pump.fun/pumpswap memecoins. You "
          "hold a position. Given the causal market snapshot and your position state, "
          "choose exactly one action: HOLD, ADD, REDUCE, EXIT. " + COST_MODEL +
          " Answer in the fixed format.")


def parse_c8(row):
    u = row["messages"][1]["content"]
    m = row["meta"]
    g = lambda rx: float(rx.search(u).group(1))
    return {
        "mint": m["mint"], "episode_id": m["episode_id"], "step": int(m["step"]),
        "old_action": m["action"], "t_dec": int(m["decision_time_unix_ms"]),
        "mark": g(RE_MARK), "entry_px": g(RE_ENTRY), "held_s": g(RE_HOLD),
        "mfe_bp": g(RE_MFE), "mae_bp": g(RE_MAE), "inv": g(RE_INV), "cash": g(RE_CASH),
        "split": m["split"],
    }


def load_tape(filepath, mints):
    """Per-mint fills in the ARCHIVE's order: (recv_unix_ms, tokens_raw).

    `load_canonical_tapes` orders ties by signature; `build_replay_v2` used
    lexsort((tokens_raw, t, mint)). For fills in the same millisecond the two orders
    disagree, so the archived entry fill is only reproducible under the archived
    order. Reproducing it is what allows the recorded entry price to be CHECKED
    instead of assumed.
    """
    import pyarrow.json as paj
    tbl = paj.read_json(filepath)
    d = tbl.to_pydict()
    keep = defaultdict(list)
    for i, m in enumerate(d["mint"]):
        if m in mints:
            keep[m].append(i)
    out, full = {}, {}
    for m, idxs in keep.items():
        idxs.sort(key=lambda i: (d["recv_unix_ms"][i], d["tokens_raw"][i]))
        sol_all = np.array([d["sol_lamports"][i] for i in idxs], dtype=np.int64)
        tok_all = np.array([d["tokens_raw"][i] for i in idxs], dtype=np.int64)
        tt_all = np.array([d["recv_unix_ms"][i] for i in idxs], dtype=np.int64)
        px_all = np.full(tt_all.size, np.nan)
        ok = tok_all != 0
        px_all[ok] = np.abs(sol_all[ok].astype(float)) / np.abs(tok_all[ok].astype(float))
        # the seed index must be read off the UNFILTERED archive-order series, or
        # dropping dust shifts it and the archived entry price stops reproducing
        full[m] = (tt_all, px_all)
        m_keep = np.isfinite(px_all) & (px_all > 0) & (np.abs(sol_all) >= MIN_NOTIONAL_LAMPORTS)
        if m_keep.sum() >= 5:
            med = float(np.median(px_all[m_keep]))
            m_keep &= (px_all >= med / MAX_PX_RATIO) & (px_all <= med * MAX_PX_RATIO)
        if m_keep.sum() < 2:
            continue
        ven = np.array([d["venue"][i] for i in idxs], dtype=object)
        sid = np.array([d["side"][i] for i in idxs], dtype=object)
        out[m] = Tape(m, tt_all[m_keep], sol_all[m_keep], tok_all[m_keep],
                      list(ven[m_keep]), list(sid[m_keep]))
    return out, full


def invert_archived(r):
    """Apply the ARCHIVED action + accounting rule to a pre-state. Returns the
    post-state and the answer to 'did the archived engine really do this?'."""
    qty, cash, cur, act = r["qty_pre"], r["cash_pre"], r["mark"], r["old_action"]
    if act == "ADD":
        add_qty = qty * 0.5
        spend = add_qty * cur * (1 + OW)
        if spend <= cash + 1e-12:
            cash -= spend
            qty += add_qty
    elif act == "REDUCE":
        sq = 0.5 * qty
        cash += sq * cur * (1 - OW)
        qty -= sq
    elif act == "EXIT":
        cash += qty * cur * (1 - OW)
        qty = 0.0
    return qty, cash


